import { test, expect, type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
const org = `/organizations/${createHash('sha256').update('10').digest('hex').slice(0,12)}`
async function login(page: Page,scenario = 'admin') {
  await page.goto(`/login?returnTo=${encodeURIComponent(`${org}/quotes/new`)}`)
  await page.getByRole('button',{name:'Open demo workspace'}).click()
  if (scenario !== 'admin') await page.getByLabel('Demo scenario').selectOption(scenario)
  await expect(page.getByLabel('Customer',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'+ Add line'})).toBeEnabled()
}
async function details(page: Page) { await page.getByLabel('Customer',{exact:true}).fill('Acme'); await page.getByLabel('Project',{exact:true}).fill('Office') }
async function add(page: Page,product='F Series') {
  await page.getByRole('button',{name:'+ Add line'}).click()
  const line = page.getByRole('article').last()
  await line.getByRole('combobox',{name:'Product',exact:true}).fill(product)
  await line.getByRole('option').filter({hasText:product}).first().click()
  await expect(line.getByRole('region',{name:'Part number segments'})).toBeVisible()
  return line
}
const save = (page:Page) => page.getByRole('button',{name:'Save',exact:true})
test('create two product lines, exact totals, reopen, edit and remove',async({page})=>{
  await login(page); await details(page)
  let line=await add(page)
  await line.getByRole('combobox',{name:'YY (position 3)'}).fill('aa')
  await line.getByRole('combobox',{name:'YY (position 3)'}).press('Tab')
  await line.getByLabel('Quantity',{exact:true}).fill('3')
  await line.getByRole('button',{name:'Done',exact:true}).click()
  await expect(line).toContainText('F-12-AA-01'); await expect(line).toContainText('$360.00')
  line=await add(page,'Product 2')
  await line.getByRole('combobox',{name:'YY (position 3)'}).fill('BZ')
  await line.getByRole('combobox',{name:'YY (position 3)'}).press('Enter')
  await line.getByLabel('Quantity',{exact:true}).fill('2')
  await line.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByText('$600.00',{exact:true})).toBeVisible()
  await save(page).click(); await expect(page).toHaveURL(/\/quotes\/\d+$/)
  await page.reload(); await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('button',{name:'Edit line 1',exact:true}).click()
  await page.getByRole('article').first().getByLabel('Quantity',{exact:true}).fill('4')
  await page.getByRole('article').first().getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByText('$720.00',{exact:true})).toBeVisible()
  page.once('dialog',d=>d.accept()); await page.getByRole('button',{name:'Remove line 2',exact:true}).click()
  await save(page).click(); await expect(page.getByRole('status').filter({hasText:'Quote saved.'})).toBeVisible(); await page.getByRole('link',{name:'Quotes',exact:true}).last().click()
  await page.getByRole('link',{name:'Acme - Office',exact:true}).click()
  await expect(page.getByRole('article')).toHaveCount(1); await expect(page.getByRole('article')).toContainText('$480.00')
})
