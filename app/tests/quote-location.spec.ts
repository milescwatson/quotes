import { test, expect } from '@playwright/test'
import { createHash } from 'node:crypto'
const org = `/organizations/${createHash('sha256').update('10').digest('hex').slice(0, 12)}`
test('Job Location saves, reloads, and marks PDF exports as stale until saved', async ({ page }) => {
  await page.goto(`/login?returnTo=${encodeURIComponent(`${org}/quotes/new`)}`)
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.getByLabel('Customer', { exact: true }).fill('Acme')
  await page.getByLabel('Project', { exact: true }).fill('Office')
  const location = page.getByLabel('Job Location', { exact: true })
  await location.fill('Seattle, WA')
  const save = page.getByRole('button', { name: 'Save changes', exact: true })
  const preview = page.getByRole('button', { name: 'Preview PDF', exact: true })
  await save.click()
  await expect(page).toHaveURL(/\/quotes\/\d+$/)
  await page.reload()
  await expect(location).toHaveValue('Seattle, WA')
  await expect(preview).toBeEnabled()
  await location.fill('Portland, OR')
  await expect(preview).toBeDisabled()
  await save.click()
  await expect(preview).toBeEnabled()
  await page.reload()
  await expect(location).toHaveValue('Portland, OR')
  await location.fill('')
  await save.click()
  await expect(preview).toBeEnabled()
  await page.reload()
  await expect(location).toHaveValue('')
})
