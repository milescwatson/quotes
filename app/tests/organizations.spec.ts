import { test,expect,type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
const org=(id='10')=>`/organizations/${createHash('sha256').update(id).digest('hex').slice(0,12)}`
async function login(page:Page,scenario='administrator') {
  await page.goto(`/login?returnTo=${encodeURIComponent(`${org()}/quotes`)}`)
  await page.getByRole('button',{name:'Open demo workspace'}).click()
  await expect(page.getByRole('heading',{name:'Quotes',exact:true})).toBeVisible()
  if(scenario!=='administrator') {
    if ((page.viewportSize()?.width || 1440) < 768) await page.getByRole('button',{name:'Toggle navigation'}).click()
    await page.getByLabel('Demo scenario').selectOption(scenario)
  }
  await page.goto(`${org()}/quotes`)
}
