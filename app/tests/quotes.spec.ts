test('filters combine, reset pagination, clear, and distinguish no matches', async ({ page }) => {
  await login(page)
  await expect(rows(page)).toHaveCount(50)
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(rows(page)).toHaveCount(5)
  await page.getByRole('button', { name: 'Customer', exact: true }).click()
  await page.getByLabel('Customer', { exact: true }).fill('customer 5')
  await page.getByLabel('Customer', { exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Project name', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('project')
  await page.getByLabel('Project name', { exact: true }).press('Enter')
  await page.getByLabel('Team member owner').selectOption('2')
  await expect(rows(page)).toHaveCount(3)
  await expect(page.getByRole('navigation', { name: 'Quotes pagination' })).toContainText('Page 1 of 1 · 3 quotes')
  await page.getByRole('button', { name: 'Customer customer 5', exact: true }).click()
  await page.getByLabel('Customer', { exact: true }).fill('no such customer')
  await expect(page.getByRole('heading', { name: 'No matching quotes.' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(rows(page)).toHaveCount(50)
  await expect(page.getByRole('button', { name: 'Customer', exact: true })).toBeVisible()
})

test('owners can be changed, unassigned, filtered, and persisted', async ({ page }) => {
  await login(page, '11')
  const owner = page.getByLabel('Owner for Forma - Office Renovation', { exact: true })
  await expect(owner).toBeEnabled()
  await owner.selectOption('2')
  await expect(page.getByText('Quote owner updated.', { exact: true })).toBeVisible()
  await expect(owner).toHaveValue('2')
  await page.reload()
  await expect(owner).toHaveValue('2')
  await page.getByLabel('Team member owner').selectOption('2')
  await expect(rows(page)).toHaveCount(1)
  await owner.selectOption('')
  await expect(page.getByRole('heading', { name: 'No matching quotes.' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(owner).toHaveValue('')
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:failure', '503'))
  await owner.selectOption('2')
  await expect(page.getByRole('alert')).toContainText('could not reach the service')
  await expect(owner).toHaveValue('')
  await owner.selectOption('2')
  await expect(owner).toHaveValue('2')
})

test('revocation during an owner update clears all visible quote rows', async ({ page }) => {
  await login(page)
  await expect(rows(page)).toHaveCount(50)
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:revoke-org', '10'))
  await rows(page).first().getByRole('combobox').selectOption('')
  await expect(page.getByRole('alert').filter({ hasText: 'no longer have access' }).first()).toBeVisible()
  await expect(rows(page)).toHaveCount(0)
})
