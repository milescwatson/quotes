import { test, expect, type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
const settings = `/organizations/${createHash('sha256').update('10').digest('hex').slice(0, 12)}/settings`
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAACXBIWXMAAAPoAAAD6AG1e1JrAAAAEUlEQVQImWNQSX79H4QZYAwAUcQJxZw+vakAAAAASUVORK5CYII=', 'base64')
async function login(page: Page) {
  await page.goto(`/login?returnTo=${encodeURIComponent(settings)}`)
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.goto(settings)
  await expect(page.getByRole('heading', { name: 'Logo', exact: true })).toBeVisible()
}
test('administrator uploads, replaces and removes a logo independently of company details', async ({ page }) => {
  await login(page)
  await page.getByLabel('Organization name', { exact: true }).fill('Unsaved company name')
  await page.getByLabel('Logo image').setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: png })
  await page.getByRole('button', { name: 'Upload logo', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Logo uploaded.' })).toBeVisible()
  await expect(page.getByAltText('Current organization logo')).toBeVisible()
  await expect(page.getByLabel('Organization name', { exact: true })).toHaveValue('Unsaved company name')
  await page.reload()
  await expect(page.getByLabel('Organization name', { exact: true })).toHaveValue('Northstar Industries')
  await expect(page.getByAltText('Current organization logo')).toBeVisible()
  await page.getByLabel('Logo image').setInputFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: png })
  await page.getByRole('button', { name: 'Replace logo', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Logo uploaded.' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove logo', exact: true }).click()
  await expect(page.getByText('No logo uploaded.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('No logo uploaded.', { exact: true })).toBeVisible()
})
test('invalid selection and failed upload recover, including on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page)
  await page.getByLabel('Logo image').setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await expect(page.getByRole('alert')).toContainText('Choose a PNG or JPEG')
  await expect(page.getByRole('button', { name: 'Upload logo', exact: true })).toBeDisabled()
  await page.getByLabel('Logo image').setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(2 * 1024 * 1024 + 1) })
  await expect(page.getByRole('alert')).toContainText('Choose a PNG or JPEG')
  await page.getByLabel('Logo image').setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: png })
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:failure', '503'))
  await page.getByRole('button', { name: 'Upload logo', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Upload logo', exact: true }).click()
  await expect(page.getByAltText('Current organization logo')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
