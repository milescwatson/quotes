test('principal choices include later pages and list retries preserve the current page', async ({ page }) => {
  await login(page)
  // Persist the seed, then add realistic later pages without changing the production adapter.
  await page.getByRole('button', { name: 'Add principal', exact: true }).click()
  await page.getByLabel('Principal name', { exact: true }).fill('Fixture principal')
  await page.getByLabel('Web address').fill('fixture-principal.com')
  await page.getByRole('button', { name: 'Create principal' }).click()
  await expect(page.locator('p[role="status"]')).toContainText('Principal added.')
  await page.evaluate(() => {
    const key = 'quotes:fixture:configurations:v1', state = JSON.parse(sessionStorage.getItem(key)!)
    for (let i = 0; i < 105; i++) state.principals.push({ id: String(500 + i), name: `Supplier ${String(i).padStart(3, '0')}`, websiteUrl: `https://supplier-${i}.com` })
    sessionStorage.setItem(key, JSON.stringify(state))
  })
  await page.reload()
  await expect(page.getByLabel('Principal', { exact: true }).locator('option')).toHaveCount(109)
  const nav = page.getByRole('navigation', { name: 'Configurations pagination' })
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:failure', '503'))
  await nav.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('could not reach')
  await expect(nav).toContainText('Page 1 of 2')
  await page.getByRole('button', { name: 'Retry configurations' }).click()
  await expect(nav).toContainText('Page 2 of 2')
  await page.getByRole('link', { name: 'New configuration' }).click()
  await page.getByLabel('Principal', { exact: true }).selectOption('604')
  await expect(page.getByLabel('Principal', { exact: true })).toHaveValue('604')
})
