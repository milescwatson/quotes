import { test, expect, type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
const org = (id = '10') => `/organizations/${createHash('sha256').update(id).digest('hex').slice(0, 12)}`
async function login(page: Page, destination = `${org()}/configurations`) {
  await page.goto(`/login?returnTo=${encodeURIComponent(destination)}`)
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
}
const save = (page: Page) => page.getByRole('button', { name: 'Save', exact: true })
async function editor(page: Page) {
  await login(page)
  await page.getByRole('link', { name: 'F Series', exact: true }).click()
  await expect(page.getByLabel('Product name', { exact: true })).toHaveValue('F Series')
}

