import { test, expect, type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
const org = (id = '10') => `/organizations/${createHash('sha256').update(id).digest('hex').slice(0, 12)}`
async function login(page: Page, destination = `${org()}/settings`) {
  await page.goto(`/login?returnTo=${encodeURIComponent(destination)}`)
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
}
const save = (page: Page) => page.getByRole('button', { name: 'Save', exact: true })
async function editor(page: Page) {
  await login(page)
  await page.getByRole('link', { name: 'F Series', exact: true }).click()
  await expect(page.getByLabel('Product name', { exact: true })).toHaveValue('F Series')
}

test('admin lists, global principal creation, name/domain duplicates and principal filter', async ({ page }) => {
  await login(page)
  const configurations = page.getByRole('region', { name: 'Product configurations table' })
  await expect(configurations.locator('tbody tr')).toHaveCount(50)
  const pagination = page.getByRole('navigation', { name: 'Configurations pagination' })
  await pagination.getByRole('button', { name: 'Next' }).click()
  await expect(configurations.locator('tbody tr')).toHaveCount(5)
  await page.getByLabel('Principal', { exact: true }).selectOption('1')
  await expect(configurations.locator('tbody tr')).toHaveCount(28)
  await expect(pagination).toContainText('Page 1 of 1')
  await page.getByRole('button', { name: 'Add principal', exact: true }).click()
  await page.getByLabel('Principal name', { exact: true }).fill('New supplier')
  await page.getByLabel('Web address').fill('https://shop.new-supplier.com/about')
  await page.getByRole('button', { name: 'Create principal' }).click()
  await expect(page.locator('p[role="status"]')).toContainText('Principal added.')
  await page.getByRole('button', { name: 'Add principal', exact: true }).click()
  await page.getByLabel('Principal name', { exact: true }).fill('New name')
  await page.getByLabel('Web address').fill('http://www.new-supplier.com/other')
  await page.getByRole('button', { name: 'Create principal' }).click()
  await expect(page.getByRole('alert')).toContainText('root domain already exists')
  await page.getByLabel('Web address').fill('different-supplier.com')
  await page.getByLabel('Principal name', { exact: true }).fill(' NEW SUPPLIER ')
  await page.getByRole('button', { name: 'Create principal' }).click()
  await expect(page.getByRole('alert')).toContainText('name already exists')
  await page.goto(`${org('11')}/taxonomies/new`)
  await expect(page.getByLabel('Principal', { exact: true }).locator('option')).toContainText(['Choose a principal', 'Acme', 'Beacon', 'New supplier'])
})

test('blank create, inline validation, currency formatting, saved IDs and no-op', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: 'New configuration' }).click()
  await expect(page.getByLabel('Product name', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Base price', { exact: true })).toHaveValue('')
  await expect(page.getByRole('region', { name: 'Configuration segments' }).locator('section')).toHaveCount(0)
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('Choose a principal')
  await page.getByLabel('Product name', { exact: true }).fill('New product')
  await page.getByLabel('Principal', { exact: true }).selectOption('1')
  await page.getByLabel('Base price', { exact: true }).fill('$1,234.567')
  await page.getByLabel('Base price', { exact: true }).blur()
  await expect(page.getByLabel('Base price', { exact: true })).toHaveValue('1234.57')
  await page.getByRole('button', { name: 'Add segment' }).click()
  await page.getByLabel('Segment 1 placeholder', { exact: true }).fill('XX')
  await page.getByRole('button', { name: 'Add option to segment 1' }).click()
  await page.getByLabel('Code for option 1 in segment 1', { exact: true }).fill('01')
  await page.getByLabel('Price for option 1 in segment 1', { exact: true }).fill('.50')
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:failure', '503'))
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('could not reach the service')
  await expect(page.getByLabel('Product name', { exact: true })).toHaveValue('New product')
  await save(page).click()
  await expect(page).toHaveURL(/\/taxonomies\/\d+$/)
  await expect(page.getByLabel('Price for option 1 in segment 1', { exact: true })).toHaveValue('0.50')
  await save(page).click()
  await expect(page.locator('p[role="status"]')).toContainText('No content changes.')
  await page.reload()
  await expect(page.getByLabel('Code for option 1 in segment 1', { exact: true })).toHaveValue('01')
  await page.getByRole('link', { name: 'Configuration Editor', exact: true }).click()
  await expect(page.getByRole('link', { name: 'New product', exact: true })).toBeVisible()
})

test('keyboard ordering preserves hidden default and principal-only save creates a version', async ({ page }) => {
  await editor(page)
  await page.getByRole('button', { name: 'Move option 1 in segment 2. Use up or down arrow keys.', exact: true }).press('ArrowDown')
  await expect(page.getByLabel('Code for option 2 in segment 2', { exact: true })).toHaveValue('12')
  await save(page).click()
  await expect(page.locator('p[role="status"]')).toContainText('Configuration saved.')
  const value = await page.evaluate(() => JSON.parse(sessionStorage.getItem('quotes:fixture:configurations:v1')!).taxonomies.find((t: any) => t.id === '100'))
  expect(value.version.content.segments[1].name).toBe('Size')
  expect(value.version.content.segments[1].defaultOptionId).toBe(value.version.content.segments[1].options[1].id)
  const number = value.version.versionNumber
  await page.getByLabel('Principal', { exact: true }).selectOption('2')
  await save(page).click()
  await expect(page.locator('p[role="status"]')).toContainText('Configuration saved.')
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('quotes:fixture:configurations:v1')!).taxonomies.find((t: any) => t.id === '100').version.versionNumber)).toBe(number + 1)
  await page.getByRole('button', { name: 'Move segment 2. Use left or right arrow keys.', exact: true }).press('ArrowLeft')
  await expect(page.getByLabel('Segment 1 placeholder', { exact: true })).toHaveValue('XX')
  await expect(page.getByLabel('Part number pattern', { exact: true })).toContainText('XX')
})

test('validation and transient save failures preserve input; stale save requires reload', async ({ page }) => {
  await editor(page)
  await page.getByLabel('Price for option 1 in segment 1', { exact: true }).fill('not a price')
  await save(page).click()
  await expect(page.getByLabel('Price for option 1 in segment 1', { exact: true })).toHaveValue('not a price')
  await expect(page.getByRole('alert')).toContainText('nonnegative USD')
  await page.getByLabel('Price for option 1 in segment 1', { exact: true }).fill('2')
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:failure', '503'))
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('could not reach the service')
  await expect(page.getByLabel('Price for option 1 in segment 1', { exact: true })).toHaveValue('2.00')
  await page.evaluate(() => sessionStorage.setItem('quotes:fixture:configuration-conflict', 'yes'))
  await save(page).click()
  await expect(page.getByRole('alert')).toContainText('configuration changed')
  await expect(save(page)).toBeDisabled()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Reload configuration' }).click()
  await expect(page.getByLabel('Price for option 1 in segment 1', { exact: true })).toHaveValue('0.00')
})

