CREATE TABLE public.principals (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    name text NOT NULL CHECK (name = btrim(name) AND length(name) BETWEEN 1 AND 120),
    normalized_name text NOT NULL CHECK (normalized_name <> ''),
    website_url text NOT NULL CHECK (length(website_url) BETWEEN 1 AND 2048),
    website_key text NOT NULL CHECK (website_key <> '' AND website_key = lower(website_key)),
    created_by_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT principals_name_unique UNIQUE (normalized_name),
    CONSTRAINT principals_website_unique UNIQUE (website_key)
);
ALTER TABLE public.taxonomies ADD COLUMN principal_id bigint;
ALTER TABLE public.taxonomy_versions ADD COLUMN principal_id bigint;
ALTER TABLE public.taxonomies ADD CONSTRAINT taxonomies_principal_fk
    FOREIGN KEY (principal_id) REFERENCES public.principals(id) ON DELETE RESTRICT NOT VALID;
ALTER TABLE public.taxonomy_versions ADD CONSTRAINT taxonomy_versions_principal_fk
    FOREIGN KEY (principal_id) REFERENCES public.principals(id) ON DELETE RESTRICT NOT VALID;
ALTER TABLE ASYNC public.taxonomies VALIDATE CONSTRAINT taxonomies_principal_fk;
ALTER TABLE ASYNC public.taxonomy_versions VALIDATE CONSTRAINT taxonomy_versions_principal_fk;
-- Enforce principal attribution on NEW snapshots without rewriting old history.
-- Intentionally NOT VALID when legacy rows have no historical principal.
ALTER TABLE public.taxonomy_versions ADD CONSTRAINT taxonomy_versions_principal_required
    CHECK (principal_id IS NOT NULL) NOT VALID;
CREATE INDEX ASYNC taxonomies_active_principal_idx
    ON public.taxonomies(owner_organization_id, principal_id, created_at, id) WHERE archived_at IS NULL;
