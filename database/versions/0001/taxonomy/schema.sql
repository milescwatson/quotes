-- Product taxonomy schema. PostgreSQL 14+; apply once with ON_ERROR_STOP enabled.
-- Then install database/functions/taxonomy.sql and this version's triggers.sql
-- before allowing writes; see database/README.md for installation order.
-- Prerequisites: public.organizations(id bigint PRIMARY KEY),
--                public.users(id bigint PRIMARY KEY).
-- These shared identity tables are intentionally not defined by this module.
-- Run through a trusted backend role, not directly from browser clients.
-- Authorization, membership roles, subscription approval, administrative audit,
-- no-op detection, and quote snapshots remain application responsibilities.
-- Do not grant the runtime role table ownership, DDL, or trigger-disable rights.
--
-- Creation: BEGIN; reserve the first version ID using
-- nextval(pg_get_serial_sequence('public.taxonomy_versions', 'id')); insert
-- taxonomy pointing to that ID RETURNING id; insert version with the reserved
-- ID, then segments/options RETURNING their generated IDs;
-- COMMIT. The two circular foreign keys are checked at commit.
-- Editing: BEGIN; SELECT taxonomy FOR UPDATE; compare current_version_id with
-- the client's expected version; insert the next full snapshot; update the
-- current_version_id; COMMIT. Never edit saved snapshot rows in place.

BEGIN;

-- Unlike numeric(14,2), an unconstrained numeric domain checks the original
-- value before any rounding. The upper bound also excludes NaN and Infinity.
CREATE DOMAIN public.taxonomy_usd_amount AS numeric
    CHECK (VALUE >= 0 AND VALUE <= 999999999999.99
           AND VALUE = trunc(VALUE, 2));

CREATE TABLE public.taxonomies (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    owner_organization_id bigint NOT NULL REFERENCES public.organizations(id),
    current_version_id bigint NOT NULL,
    created_by_user_id bigint NOT NULL REFERENCES public.users(id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived_at timestamptz,
    CONSTRAINT taxonomy_archive_time CHECK (archived_at >= created_at)
);

CREATE INDEX taxonomies_owner_idx ON public.taxonomies(owner_organization_id);

CREATE TABLE public.taxonomy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    taxonomy_id bigint NOT NULL REFERENCES public.taxonomies(id),
    version_number integer NOT NULL CHECK (version_number > 0),
    product_family_name text NOT NULL
        CHECK (product_family_name <> '' AND product_family_name !~ '^[[:space:]]|[[:space:]]$'),
    base_price public.taxonomy_usd_amount NOT NULL DEFAULT 0.00,
    currency text NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
    created_by_user_id bigint NOT NULL REFERENCES public.users(id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_summary text,
    -- Internal marker: children may be inserted only in this transaction.
    -- Assigned by a trigger, never accepted from caller input.
    created_in_transaction xid8 NOT NULL DEFAULT pg_current_xact_id(),
    CONSTRAINT taxonomy_version_number_unique UNIQUE (taxonomy_id, version_number),
    CONSTRAINT taxonomy_version_identity_unique UNIQUE (taxonomy_id, id)
);

ALTER TABLE public.taxonomies ADD CONSTRAINT taxonomy_current_version_fk
    FOREIGN KEY (id, current_version_id)
    REFERENCES public.taxonomy_versions(taxonomy_id, id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE public.taxonomy_version_segments (
    version_id bigint NOT NULL REFERENCES public.taxonomy_versions(id),
    segment_id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1),
    position integer NOT NULL CHECK (position >= 0),
    placeholder text NOT NULL
        CHECK (placeholder <> '' AND placeholder !~ '^[[:space:]]|[[:space:]]$'),
    name text CHECK (name <> '' AND name !~ '^[[:space:]]|[[:space:]]$'),
    default_option_id bigint,
    PRIMARY KEY (version_id, segment_id),
    CONSTRAINT taxonomy_segment_position_unique UNIQUE (version_id, position)
);

CREATE UNIQUE INDEX taxonomy_segment_placeholder_unique
    ON public.taxonomy_version_segments(version_id, lower(placeholder));
CREATE UNIQUE INDEX taxonomy_segment_name_unique
    ON public.taxonomy_version_segments(version_id, lower(name)) WHERE name IS NOT NULL;

CREATE TABLE public.taxonomy_version_options (
    version_id bigint NOT NULL,
    segment_id bigint NOT NULL,
    option_id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1),
    position integer NOT NULL CHECK (position >= 0),
    code text NOT NULL CHECK (code <> '' AND code !~ '[[:space:]-]'),
    description text CHECK (description ~ '[^[:space:]]'),
    price public.taxonomy_usd_amount NOT NULL DEFAULT 0.00,
    PRIMARY KEY (version_id, segment_id, option_id),
    CONSTRAINT taxonomy_option_segment_fk FOREIGN KEY (version_id, segment_id)
        REFERENCES public.taxonomy_version_segments(version_id, segment_id),
    CONSTRAINT taxonomy_option_position_unique UNIQUE (version_id, segment_id, position)
);

CREATE UNIQUE INDEX taxonomy_option_code_unique
    ON public.taxonomy_version_options(version_id, segment_id, lower(code));

ALTER TABLE public.taxonomy_version_segments ADD CONSTRAINT taxonomy_segment_default_fk
    FOREIGN KEY (version_id, segment_id, default_option_id)
    REFERENCES public.taxonomy_version_options(version_id, segment_id, option_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE public.taxonomy_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    taxonomy_id bigint NOT NULL REFERENCES public.taxonomies(id),
    subscriber_organization_id bigint NOT NULL REFERENCES public.organizations(id),
    granted_by_user_id bigint NOT NULL REFERENCES public.users(id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at timestamptz,
    revoked_by_user_id bigint REFERENCES public.users(id),
    CONSTRAINT taxonomy_subscription_revocation_pair
        CHECK ((revoked_at IS NULL) = (revoked_by_user_id IS NULL)),
    CONSTRAINT taxonomy_subscription_revocation_time CHECK (revoked_at >= created_at)
);

CREATE UNIQUE INDEX taxonomy_subscription_active_unique
    ON public.taxonomy_subscriptions(taxonomy_id, subscriber_organization_id)
    WHERE revoked_at IS NULL;
CREATE INDEX taxonomy_subscription_active_subscriber_idx
    ON public.taxonomy_subscriptions(subscriber_organization_id, taxonomy_id)
    WHERE revoked_at IS NULL;
CREATE INDEX taxonomy_subscription_history_idx
    ON public.taxonomy_subscriptions(taxonomy_id, created_at);

COMMENT ON DOMAIN public.taxonomy_usd_amount IS
    'USD: 0 through 999999999999.99, rejects fractional cents instead of rounding.';
COMMENT ON TABLE public.taxonomy_versions IS
    'Immutable complete snapshots. Create segments/options in the same transaction as the version.';
COMMENT ON COLUMN public.taxonomy_versions.created_at IS
    'Transaction-start timestamp, not an exact wall-clock commit timestamp.';
COMMENT ON COLUMN public.taxonomy_versions.created_in_transaction IS
    'Internal immutable snapshot construction guard using the full transaction ID.';

-- Quote integration (when quote tables exist): persist part_number text,
-- product_family_name, currency, base_price, unit_price, configuration_snapshot
-- jsonb, source_taxonomy_id and source_version_id. Use a composite FK from
-- (source_taxonomy_id, source_version_id) to taxonomy_versions(taxonomy_id, id).
-- Quote reads must use those saved values, never reprice from current versions.
-- No quote tables or identity/authorization policies are invented here.

COMMIT;
