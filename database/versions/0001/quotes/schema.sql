-- Apply after database/versions/0001/identity/schema.sql, one DDL statement per transaction.
-- Record the INDEX ASYNC job_id and wait for successful completion before release.
CREATE TABLE public.quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
    customer_id integer,
    owner_user_id bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    customer_name text NOT NULL
        CHECK (customer_name = btrim(customer_name) AND length(customer_name) BETWEEN 1 AND 120),
    project_name text NOT NULL
        CHECK (project_name = btrim(project_name) AND length(project_name) BETWEEN 1 AND 120),
    modified_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    modified_when timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ASYNC quotes_organization_modified_idx
    ON public.quotes(organization_id, modified_when, id);

