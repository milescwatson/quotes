-- First installation of the JSONB taxonomy module, after 0001 identity/quotes.
-- Preconditions: neither public.taxonomies nor public.taxonomy_versions exists.
-- Stop on any error. Execute ONE statement per transaction on Aurora DSQL.
-- Do not run the legacy 0001 taxonomy schema/functions/triggers first.
CREATE TABLE public.taxonomies (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    owner_organization_id bigint NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
    current_version_id bigint NOT NULL,
    created_by_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived_at timestamptz,
    archived_by_user_id bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    CHECK ((archived_at IS NULL) = (archived_by_user_id IS NULL)),
    CHECK (archived_at IS NULL OR archived_at >= created_at)
);
CREATE TABLE public.taxonomy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
    taxonomy_id bigint NOT NULL REFERENCES public.taxonomies(id) ON DELETE RESTRICT,
    version_number integer NOT NULL CHECK (version_number > 0),
    content jsonb NOT NULL CHECK (
        jsonb_typeof(content) = 'object'
        AND content ? 'schemaVersion'
        AND content->'schemaVersion' = '1'::jsonb
        AND content ? 'segments'
        AND jsonb_typeof(content->'segments') = 'array'
    ),
    created_by_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_summary text CHECK (length(change_summary) BETWEEN 1 AND 500),
    CONSTRAINT taxonomy_version_number_unique UNIQUE (taxonomy_id, version_number),
    CONSTRAINT taxonomy_version_identity_unique UNIQUE (taxonomy_id, id)
);
-- DSQL requires NOT VALID for an added foreign key; validate before traffic.
ALTER TABLE public.taxonomies ADD CONSTRAINT taxonomy_current_version_fk
    FOREIGN KEY (id, current_version_id) REFERENCES public.taxonomy_versions(taxonomy_id, id)
    DEFERRABLE INITIALLY DEFERRED NOT VALID;
ALTER TABLE ASYNC public.taxonomies VALIDATE CONSTRAINT taxonomy_current_version_fk;
CREATE INDEX ASYNC taxonomies_active_owner_idx
    ON public.taxonomies(owner_organization_id, created_at, id) WHERE archived_at IS NULL;
