CREATE TABLE public.regular_products (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES public.organizations(id),
  part_number text NOT NULL CHECK (part_number = trim(part_number) AND length(part_number) BETWEEN 1 AND 120),
  description text NOT NULL DEFAULT '' CHECK (length(description) <= 500),
  list_price numeric(14,2) NOT NULL CHECK (list_price >= 0),
  parent_taxonomy_id bigint REFERENCES public.taxonomies(id),
  modified_when timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT regular_product_number_unique UNIQUE (organization_id, part_number)
);
